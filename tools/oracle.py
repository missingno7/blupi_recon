def postprocess_code(rows, crt_split):
    pe = pefile.PE(str(PRIMARY), fast_load=False)
    image_base = pe.OPTIONAL_HEADER.ImageBase
    entry = pe.OPTIONAL_HEADER.AddressOfEntryPoint
    func_by_rva = {row["rva"]: row for row in rows}
    starts = {image_base + row["rva"] for row in rows}
    pointer_runs = []
    for sec in pe.sections:
        name = decode(sec.Name).strip("\0")
        if name.lower() not in (".rdata", ".data"):
            continue
        raw = bytes(pe.__data__[sec.PointerToRawData:sec.PointerToRawData + sec.SizeOfRawData])
        words = []
        for off in range(0, len(raw) - 3, 4):
            value = struct.unpack_from("<I", raw, off)[0]
            if value in starts:
                words.append((off, value))
            else:
                words.append((off, None))
        i = 0
        while i < len(words):
            if words[i][1] is None:
                i += 1
                continue
            j = i + 1
            while j < len(words) and words[j][1] is not None and words[j][0] == words[j-1][0] + 4:
                j += 1
            if j - i >= 2:
                rva = sec.VirtualAddress + words[i][0]
                methods = [func_by_rva.get(val - image_base, {}).get("name", f"0x{val-image_base:x}") for _, val in words[i:j]]
                pointer_runs.append({"section": name, "rva": f"0x{rva:x}", "count": j-i, "methods": methods})
            i = j
    (OUT / "pointer_runs.json").write_text(json.dumps(pointer_runs, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    vtable_candidates = [run for run in pointer_runs if len(set(run["methods"])) >= 2]
    with (CANON / "vtables.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(("section", "rva", "count", "methods", "evidence"))
        for run in vtable_candidates:
            writer.writerow((run["section"], run["rva"], run["count"], "|".join(run["methods"]), "consecutive pointers to distinct Ghidra function entries; candidate vtable"))
    marker_hits = []
    data = Path(PRIMARY).read_bytes()
    for marker in (b".?AV", b".?AU", b".?AT", b".?AW"):
        pos = 0
        while True:
            pos = data.find(marker, pos)
            if pos < 0:
                break
            marker_hits.append({"marker": marker.decode(), "file_offset": f"0x{pos:x}"})
            pos += 1
    (OUT / "rtti_markers.json").write_text(json.dumps(marker_hits, indent=2) + "\n", encoding="utf-8")
    strings = []
    for sec in pe.sections:
        section = decode(sec.Name).strip("\0")
        if section.lower() not in (".rdata", ".data"):
            continue
        raw = bytes(pe.__data__[sec.PointerToRawData:sec.PointerToRawData + sec.SizeOfRawData])
        # printable single-byte C strings
        for match in re.finditer(rb"[\x20-\x7e]{4,}\x00", raw):
            value = match.group()[:-1].decode("ascii", "replace")
            strings.append((section, f"0x{sec.VirtualAddress + match.start():x}", "ascii", value))
        # printable UTF-16LE C strings, only at even offsets
        for pos in range(0, len(raw) - 8, 2):
            if pos >= 2 and 0x20 <= raw[pos-2] <= 0x7e and raw[pos-1] == 0:
                continue
            end = pos
            chars = []
            while end + 1 < len(raw):
                lo, hi = raw[end], raw[end+1]
                if hi == 0 and 0x20 <= lo <= 0x7e:
                    chars.append(chr(lo)); end += 2
                else:
                    break
            if len(chars) >= 4 and end + 1 < len(raw) and raw[end:end+2] == b"\0\0":
                strings.append((section, f"0x{sec.VirtualAddress + pos:x}", "utf16le", "".join(chars)))
    dedup = list(dict.fromkeys(strings))
    with (OUT / "strings.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(("section", "rva", "encoding", "value"))
        writer.writerows(dedup)
    ranges = read_function_ranges()
    write_key_disassembly(pe, ranges)
    resource_strings, resource_blocks = extract_resource_strings(pe)
    with (OUT / "resource_strings.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(("string_id", "block_id", "language_id", "language", "string_rva", "block_rva", "value"))
        for item in resource_strings:
            writer.writerow((item["string_id"], item["block_id"], item["language_id"], item["language"], item["string_rva"], item["block_rva"], item["value"]))
    data_record = {
        "function_count": len(rows),
        "function_kind_counts": dict(Counter("thunk" if row["thunk"] else "crt/library" if row["rva"] >= crt_split else "game" for row in rows)),
        "function_body_bytes_by_kind": dict(Counter({kind: sum(row["body_bytes"] for row in rows if ("thunk" if row["thunk"] else "crt/library" if row["rva"] >= crt_split else "game") == kind) for kind in ("game", "crt/library", "thunk")})),
        "crt_split_rva": f"0x{crt_split:x}",
        "entry_rva": f"0x{entry:x}",
        "winmain_rva": "0x1e30",
        "multi_range_functions": sum(len(v) > 1 for v in ranges.values()),
        "consecutive_function_pointer_runs": len(pointer_runs),
        "candidate_vtables": len(vtable_candidates),
        "rtti_marker_count": len(marker_hits),
        "string_count": len(dedup),
        "string_count_by_section": dict(Counter(item[0] for item in dedup)),
        "string_rva_ranges": {name: {"min": f"0x{min(int(item[1], 16) for item in dedup if item[0] == name):x}", "max": f"0x{max(int(item[1], 16) for item in dedup if item[0] == name):x}"} for name in sorted({item[0] for item in dedup})},
        "resource_string_block_count": len(resource_blocks),
        "resource_string_count": len(resource_strings),
        "resource_string_block_ids": sorted({item["block_id"] for item in resource_strings}),
        "resource_string_languages": sorted({item["language"] for item in resource_strings}),
        "resource_string_rva_range": {"min": min((item["block_rva"] for item in resource_blocks), default=""), "max": max((item["block_end_rva"] for item in resource_blocks), default="")},
    }
    (OUT / "code_summary.json").write_text(json.dumps(data_record, indent=2) + "\n", encoding="utf-8")
    print(f"Consecutive function-pointer runs: {len(pointer_runs)}; distinct-target vtable candidates: {len(vtable_candidates)}; RTTI name markers: {len(marker_hits)}; strings: {len(dedup)}")


def write_key_disassembly(pe, ranges):
    image_base = pe.OPTIONAL_HEADER.ImageBase
    labels = {
        0x1e30: "WinMain (inferred from four-argument startup call)",
        pe.OPTIONAL_HEADER.AddressOfEntryPoint: "WinMainCRTStartup (PE entry)",
        0x24140: "__global_unwind2 (first recognized CRT helper; split anchor)",
        0x24750: "_strncpy (recognized CRT helper)",
        0x2a260: "__aulldiv (recognized CRT helper)",
        0x2a2d0: "__aullrem (recognized CRT helper)",
        0x2ae30: "_abort (recognized CRT helper)",
    }
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    with (OUT / "startup_disassembly.txt").open("w", encoding="utf-8") as stream:
        for rva, label in labels.items():
            if rva not in ranges:
                continue
            stream.write(f"\n## {label} at RVA 0x{rva:x}\n")
            for start, end in ranges[rva]:
                stream.write(f"# body range 0x{start:x}..0x{end:x} (end exclusive)\n")
                for ins in md.disasm(pe.get_data(start, end - start), image_base + start):
                    ins_rva = ins.address - image_base
                    stream.write(f"{ins_rva:08x}  {ins.bytes.hex():<20} {ins.mnemonic} {ins.op_str}\n")


def extract_resource_strings(pe):
    strings = []
    blocks = []
    for root in getattr(pe, "DIRECTORY_ENTRY_RESOURCE", None).entries if hasattr(pe, "DIRECTORY_ENTRY_RESOURCE") else []:
        if root.id != 6 or not root.struct.DataIsDirectory:  # RT_STRING
            continue
        for block in root.directory.entries:
            if block.id is None or not block.struct.DataIsDirectory:
                continue
            for lang in block.directory.entries:
                if lang.struct.DataIsDirectory:
                    continue
                resource = lang.data
                block_rva = resource.struct.OffsetToData
                block_size = resource.struct.Size
                blocks.append({"block_id": block.id, "language_id": lang.id, "block_rva": f"0x{block_rva:x}", "block_end_rva": f"0x{block_rva + block_size:x}"})
                raw = pe.get_data(block_rva, block_size)
                off = 0
                for index in range(16):
                    if off + 2 > len(raw):
                        break
                    length = struct.unpack_from("<H", raw, off)[0]
                    off += 2
                    char_bytes = length * 2
                    if off + char_bytes > len(raw):
                        break
                    value = raw[off:off + char_bytes].decode("utf-16le", "replace")
                    string_rva = block_rva + off
                    if value:
                        strings.append({
                            "string_id": (block.id - 1) * 16 + index,
                            "block_id": block.id,
                            "language_id": f"0x{lang.id:04x}",
                            "language": lang_name(lang.id),
                            "string_rva": f"0x{string_rva:x}",
                            "block_rva": f"0x{block_rva:x}",
                            "value": value,
                        })
                    off += char_bytes
    return strings, blocks


def verify_boundaries():
    pe = pefile.PE(str(PRIMARY), fast_load=True)
    ranges = read_function_ranges()
    functions = []
    with (CANON / "functions.csv").open(newline="", encoding="utf-8") as f:
        functions = list(csv.DictReader(f))
    candidates = [int(row["rva"], 16) for row in functions if int(row["rva"], 16) in ranges and len(ranges[int(row["rva"], 16)]) == 1]
    sample = random.Random(0x19981014).sample(candidates, 10)
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    outcomes = []
    for start in sorted(sample):
        range_start, range_end = ranges[start][0]
        code = pe.get_data(range_start, range_end - range_start)
        insns = list(md.disasm(code, pe.OPTIONAL_HEADER.ImageBase + range_start))
        actual_end = insns[-1].address + insns[-1].size if insns else pe.OPTIONAL_HEADER.ImageBase + range_start
        expected_end = pe.OPTIONAL_HEADER.ImageBase + range_end
        ok = bool(insns) and insns[0].address == pe.OPTIONAL_HEADER.ImageBase + range_start and actual_end == expected_end
        outcomes.append({"rva": f"0x{start:x}", "function": func_name_from_csv(functions, start), "range": [f"0x{range_start:x}", f"0x{range_end:x}"], "first": insns[0].mnemonic + " " + insns[0].op_str if insns else "undecoded", "last": insns[-1].mnemonic + " " + insns[-1].op_str if insns else "undecoded", "instruction_count": len(insns), "ok": ok})
    path = OUT / "boundary_spotcheck.json"
    path.write_text(json.dumps(outcomes, indent=2) + "\n", encoding="utf-8")
    passed = sum(item["ok"] for item in outcomes)
    print(f"Capstone spot-check: {passed}/10 sampled function bodies decoded from Ghidra start through end; see {path}")
    if passed != 10:
        raise RuntimeError("one or more sampled function boundaries did not decode exactly")


def func_name_from_csv(rows, start):
    for row in rows:
        if int(row["rva"], 16) == start:
            return row["name"]
    return "unknown"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("extract", "inventory", "functions", "verify", "all"))
    parser.add_argument("--keep-iso", action="store_true", help="do not clear the extracted ISO folder before extracting")
    parser.add_argument("--fresh", action="store_true", help="for all: remove generated build/oracle output before regenerating")
    args = parser.parse_args()
    if args.fresh and args.command != "all":
        parser.error("--fresh is only valid with the all command")
    if args.fresh and OUT.exists():
        safe_rmtree(OUT)
    if args.command == "extract":
        extract_iso(clean=not args.keep_iso)
        print(f"Extracted ISO to {OUT / 'iso'}")
    elif args.command == "inventory":
        run_inventory()
    elif args.command == "functions":
        ghidra_export()
    elif args.command == "verify":
        verify_boundaries()
    else:
        extract_iso(clean=not args.keep_iso)
        run_inventory()
        ghidra_export()


if __name__ == "__main__":
    main()
