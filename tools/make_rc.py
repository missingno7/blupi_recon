"""Generate src/res/blupi.rc (Speedy Blupi 1 resources) and copy the original Planet Blupi cursor/icon files.

Provenance (docs/RESOURCES.md): the 14 cursors and the icon are Planet Blupi's original 1997 resource files
(external/planetblupi commit b0270ab), byte-identical to the oracle's RT_CURSOR/RT_ICON payloads. The string table and
the one dialog are reconstructed as resource-script text from the oracle's RT_STRING/RT_DIALOG resources; the version
block follows Planet Blupi's script with the oracle's Speedy Blupi values. Statement order follows Planet Blupi's script
(icon, version, cursors) plus the dialog and string table, matching the oracle's resource data order.

  .pyenv\\python.exe tools\\make_rc.py
"""
import struct, subprocess
from pathlib import Path
import pefile

ROOT = Path(__file__).resolve().parents[1]
ORACLE = ROOT / "assets/Speedy Blupi/BLUPI.EXE"
OUT = ROOT / "src/res"
PB_FILES = ["cursor1.cur", "map.cur", "arrowup.cur", "arrowdow.cur", "arrowlef.cur", "arrowrig.cur", "arrowul.cur",
            "arrowur.cur", "arrowdr.cur", "arrowdl.cur", "wait.cur", "empty.cur", "fill.cur", "arrow.cur", "blupi.ico"]
CURSORS = [("IDC_POINTER", "cursor1.cur"), ("IDC_MAP", "map.cur"), ("IDC_ARROWU", "arrowup.cur"), ("IDC_ARROWD", "arrowdow.cur"),
           ("IDC_ARROWL", "arrowlef.cur"), ("IDC_ARROWR", "arrowrig.cur"), ("IDC_ARROWUL", "arrowul.cur"),
           ("IDC_ARROWUR", "arrowur.cur"), ("IDC_ARROWDR", "arrowdr.cur"), ("IDC_ARROWDL", "arrowdl.cur"),
           ("IDC_WAIT", "wait.cur"), ("IDC_EMPTY", "empty.cur"), ("IDC_FILL", "fill.cur"), ("IDC_ARROW", "arrow.cur")]


def strings(pe):
    out = []
    for t in pe.DIRECTORY_ENTRY_RESOURCE.entries:
        if t.id != 6:
            continue
        # RC emits string blocks in order of first appearance in the script: the oracle's data order
        # (ascending data offsets) records the original script's block order.
        for e in sorted(t.directory.entries, key=lambda e: e.directory.entries[0].data.struct.OffsetToData):
            l = e.directory.entries[0]
            d = pe.get_data(l.data.struct.OffsetToData, l.data.struct.Size)
            o = 0
            for k in range(16):
                n = struct.unpack_from("<H", d, o)[0]; o += 2
                if n:
                    out.append(((e.id - 1) * 16 + k, d[o:o + 2 * n].decode("utf-16-le")))
                o += 2 * n
    return out


def rcstr(s):
    r = []
    for ch in s:
        if ch == '"': r.append('""')
        elif ch == "\\": r.append("\\\\")
        elif ch == "\n": r.append("\\n")
        elif ch == "\r": r.append("\\r")
        elif ch == "\t": r.append("\\t")
        else: r.append(ch)
    return '"' + "".join(r) + '"'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for f in PB_FILES:
        data = subprocess.run(["git", "-C", str(ROOT / "external/planetblupi"), "show", "b0270ab:" + f],
                              check=True, capture_output=True).stdout
        (OUT / f).write_bytes(data)
    pe = pefile.PE(str(ORACLE))
    L = ["// Speedy Blupi 1 resources. Generated by tools/make_rc.py; provenance in docs/RESOURCES.md.", "",
         '#include "afxres.h"', "",
         "LANGUAGE LANG_NEUTRAL, SUBLANG_NEUTRAL", "#pragma code_page(1252)", "",
         'IDR_MAINFRAME           ICON    DISCARDABLE     "blupi.ico"', "",
         "1 VERSIONINFO", " FILEVERSION 0,4,0,0", " PRODUCTVERSION 0,4,0,0", " FILEFLAGSMASK 0x3fL", " FILEFLAGS 0x0L",
         " FILEOS 0x40004L", " FILETYPE 0x1L", " FILESUBTYPE 0x0L", "BEGIN", '    BLOCK "StringFileInfo"', "    BEGIN",
         '        BLOCK "100c04b0"', "        BEGIN",
         '            VALUE "CompanyName", "EPSITEC\\0"', '            VALUE "FileDescription", "Blupi\\0"',
         '            VALUE "FileVersion", "0, 4, 0, 0\\0"', '            VALUE "InternalName", "Speedy Blupi\\0"',
         '            VALUE "LegalCopyright", "Copyright \xa9 1997 Epsitec SA\\0"', '            VALUE "OriginalFilename", "Blupi.exe\\0"',
         '            VALUE "ProductName", "EPSITEC Speedy Blupi\\0"', '            VALUE "ProductVersion", "0, 4, 0, 0\\0"',
         "        END", "    END", '    BLOCK "VarFileInfo"', "    BEGIN", '        VALUE "Translation", 0x100c, 1200', "    END",
         "END", ""]
    for name, f in CURSORS:
        L.append(f'{name:<23} CURSOR  DISCARDABLE     "{f}"')
    L += ["", "LANGUAGE LANG_FRENCH, SUBLANG_FRENCH_SWISS", "",
          "// Dialog 111: original symbolic name unknown.",
          "111 DIALOG DISCARDABLE  140, 100, 123, 77",
          "STYLE DS_MODALFRAME | WS_POPUP | WS_CAPTION | WS_SYSMENU", 'CAPTION "Blupi"', 'FONT 8, "MS Sans Serif"', "BEGIN",
          "    EDITTEXT        1000,7,21,108,12,ES_AUTOHSCROLL",
          '    DEFPUSHBUTTON   "OK",IDOK,7,56,50,14',
          '    PUSHBUTTON      "Cancel",IDCANCEL,66,56,50,14',
          '    LTEXT           "Player\'s name :",IDC_STATIC,7,7,109,12', "END", "",
          "LANGUAGE LANG_NEUTRAL, SUBLANG_NEUTRAL", "", "STRINGTABLE DISCARDABLE", "BEGIN"]
    for sid, s in strings(pe):
        L.append(f"    {sid:<5} {rcstr(s)}")
    L += ["END", ""]
    text = "\r\n".join(L)
    (OUT / "blupi.rc").write_bytes(text.encode("cp1252"))
    print("wrote", OUT / "blupi.rc")


if __name__ == "__main__":
    main()
