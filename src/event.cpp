void CEvent::ReadInput()
{
	BOOL bAllowDiagonalDown;
	int  i;
	UINT newKeyPress;
	BOOL bSkateboard;
	BOOL bHelicopter;
	BOOL bCar;
	BOOL bWater;
	JOYINFOEX joyInfo;
	UINT joyID;


	if (m_bMulti)
	{
		m_pDecor->TreatNetData();
	}
	
	if (m_joyIndex == NULL || m_bDemoPlay) 
	{
		m_pDecor->SetJoystickEnable(FALSE);
	}
	else
	{
		m_pDecor->GetBlupiInfo(&bHelicopter, &bCar, &bSkateboard, &bWater);
		bAllowDiagonalDown = TRUE;

		if (bHelicopter || bCar || bSkateboard)
		{
			bAllowDiagonalDown = FALSE;
		}
		joyID = m_joyID;
		ZeroMemory(&joyInfo, sizeof(JOYINFOEX));
		joyInfo.dwSize = 52;
		joyInfo.dwFlags = JOY_RETURNALL;

		if (joyGetPosEx(joyID, &joyInfo) == JOYERR_NOERROR)
		{
			m_keyPress = 0;

			if ((int)joyInfo.dwXpos < 16384)
			{
				m_keyPress = KEY_LEFT;
			}
			if ((int)joyInfo.dwXpos > 49152)
			{
				m_keyPress |= KEY_RIGHT;
			}
			if (m_keyPress == KEY_NONE && (int)joyInfo.dwYpos < 16384)
			{
				m_keyPress = KEY_UP;
			}
			if ((m_keyPress == KEY_NONE || bAllowDiagonalDown) && (int)joyInfo.dwYpos > 49152)
			{
				m_keyPress |= KEY_DOWN;
			}
			if ((BYTE)joyInfo.dwButtons & JOY_BUTTON1)
			{
				m_keyPress = m_keyPress & ~(KEY_DOWN | KEY_UP) | KEY_JUMP;
			}
			if ((BYTE)joyInfo.dwButtons & JOY_BUTTON2)
			{
				if (bSkateboard)
				{
					m_keyPress = m_keyPress & ~(KEY_DOWN | KEY_UP) | KEY_JUMP;
					
				}
				else
				{
					m_keyPress = m_keyPress & ~KEY_DOWN | KEY_UP | KEY_JUMP;
				}
			}
			if ((BYTE)joyInfo.dwButtons & JOY_BUTTON3)
			{
				if (bHelicopter)
				{
					m_keyPress = m_keyPress | KEY_DOWN;
				}
				else
				{
					if (bSkateboard)
					{
						m_keyPress = m_keyPress & ~(KEY_DOWN | KEY_UP) | KEY_JUMP;
					}
					else
					{
						m_keyPress = m_keyPress | KEY_DOWN | KEY_JUMP;
					}
				}
				m_keyPress &= ~KEY_UP; // lol
			}
			if ((BYTE)joyInfo.dwButtons & JOY_BUTTON4)
			{
				m_keyPress = m_keyPress & ~(KEY_DOWN | KEY_UP) | KEY_FIRE;
			}
			m_pDecor->KeyChange(m_keyPress);
			m_pDecor->SetJoystickEnable(TRUE);
		}
	}
}

