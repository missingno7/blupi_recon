void CEvent::PutTextInputBox(POINT pos)
{
	char textInput[100];
	int	 lg;
	int  num;
	UINT textHili;
	LONG posD;

	lg = GetTextWidth(m_textInput, 0);
	posD = pos.x - lg / 2;
	
	if (0 < m_textHiliStart)
	{
		memcpy(textInput, m_textInput, m_textHiliStart);
		textInput[m_textHiliStart] = 0;
		pos.x = posD;
		pos.y = pos.y;
		DrawTextLeft(m_pPixmap, pos, textInput, 0);
		lg = GetTextWidth(textInput, 0);
		posD += lg;
	}
	if (m_textHiliStart < m_textHiliEnd)
	{
		textHili = m_textHiliEnd - m_textHiliStart;
		memcpy(textInput, m_textInput + m_textHiliStart, textHili);
		textInput[textHili] = 0;
		pos.x = posD;
		pos.y = pos.y;
		DrawTextLeft(m_pPixmap, pos, textInput, 2);
		posD += GetTextWidth(textInput, 0);
	}
	if (m_textCursorIndex % 16 < 8)
	{
		pos.x = posD;
		pos.y = pos.y;
		DrawTextLeft(m_pPixmap, pos, (char*)"|", 0);
	}

	if (m_textHiliEnd < (int)strlen(m_textInput))
	{
		pos.x = posD;
		pos.y = pos.y;
		strcpy(textInput, m_textInput + m_textHiliEnd);
		DrawTextLeft(m_pPixmap, pos, textInput, 0);
	}
	m_textCursorIndex++;
}

BOOL CEvent::TextInputDelete()
{
	int start;

	start = m_textHiliStart;
	if (start < m_textHiliEnd)
	{
		do {
			m_textInput[start] = m_textInput[m_textHiliEnd + start - m_textHiliStart];
			start++;
		} while (m_textInput[start - 1] != 0);

		m_textHiliEnd = m_textHiliStart;
		return TRUE;
	}
	return FALSE;
}

BOOL CEvent::TreatTextInput(UINT message, WPARAM wParam, LPARAM lParam) {
	int len, i;
	if (message == WM_CHAR)
	{
		TextInputDelete();
		len = strlen(m_textInput);
		if (len < 40 && wParam >= 0x20 && wParam <= 0xff)
		{
			for (i = len + 1; i > m_textHiliStart; i--)
			{
				m_textInput[i] = m_textInput[i - 1];
			}
			m_textInput[m_textHiliStart] = wParam;
			m_textHiliStart++;
			m_textHiliEnd++;
			m_textCursorIndex = 0;
			return TRUE;
		}
	}
	if (message == WM_KEYDOWN)
	{
	if (wParam == VK_BACK && !TextInputDelete() && m_textHiliStart > 0)
	{
		len = strlen(m_textInput);
		for (i = m_textHiliStart - 1; i < len; i++)
		{
			m_textInput[i] = m_textInput[i + 1];
		}
		m_textHiliStart--;
		m_textHiliEnd--;
		m_textCursorIndex = 0;
		return TRUE;
	}
	if (wParam == VK_DELETE && !TextInputDelete())
	{
		len = strlen(m_textInput);
		if (m_textHiliStart < len)
		{
			for (i = m_textHiliStart; i < len; i++)
			{
				m_textInput[i] = m_textInput[i + 1];
			}
			m_textCursorIndex = 0;
			return TRUE;
		}
	}
	if (wParam == VK_LEFT)
	{
		if (m_textHiliStart < m_textHiliEnd) m_textHiliEnd = m_textHiliStart;
		if (m_textHiliStart > 0)
		{
			m_textHiliStart--;
			m_textHiliEnd--;
			m_textCursorIndex = 0;
			return TRUE;
		}
		else
		{
			m_textCursorIndex = 0;
			return TRUE;
		}
	}
	if (wParam == VK_RIGHT)
	{
		len = strlen(m_textInput);
		if (m_textHiliStart < m_textHiliEnd) m_textHiliStart = m_textHiliEnd;
		if (m_textHiliStart < len)
		{
			m_textHiliStart++;
			m_textHiliEnd++;
		}
		m_textCursorIndex = 0;
		return TRUE;
	}
	if (wParam == VK_UP || wParam == VK_HOME)
	{
		m_textHiliStart = 0;
		m_textHiliEnd = 0;
		m_textCursorIndex = 0;
		return TRUE;
	}
	if (wParam == VK_DOWN || wParam == VK_END)
	{
		m_textHiliStart = strlen(m_textInput);
		m_textHiliEnd = m_textHiliStart;
		m_textCursorIndex = 0;
		return TRUE;
	}
	}
	return FALSE;
}

