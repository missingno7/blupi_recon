int CEvent::MousePosToSprite(POINT pos)
{
	int sprite;

	sprite = SPRITE_POINTER;

	if (m_phase != WM_PHASE_PLAY &&
		m_phase != WM_PHASE_PLAYTEST &&
		m_phase != WM_PHASE_BUILD &&
		m_phase != WM_PHASE_BYE &&
		!MouseOnButton(pos))
	{
		sprite = SPRITE_ARROW;
	}
	if (m_bWaitMouse)
	{
		sprite = SPRITE_WAIT;
	}
	if (m_bHideMouse)
	{
		sprite = SPRITE_EMPTY;
	}
	if (m_bDisableMouse)
	{
		sprite = SPRITE_DISABLE;
	}

	return sprite;
}

