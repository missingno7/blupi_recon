		if (message == WM_BUTTON10)
		{
			m_filePageOffset = m_filePageOffset + -6;
			if (m_filePageOffset < 0)
				m_filePageOffset = 0;
		}
		if (message == WM_BUTTON11)
			m_filePageOffset += 6;
